import { initializeDatabase } from '../src/database/database';
import { saveHabit, saveReward } from '../src/database/habits';
import * as L from '../src/database/ledger';
import assert from 'node:assert';
initializeDatabase();
const h = saveHabit({ name: 'Read', points: 10, reminder_time: null });
const r = saveReward({ name: 'Pizza', cost: 15 });
assert.deepEqual(L.checkIn(h), { ok: true });
assert.equal(L.getBalance(), 10);
assert.equal(L.checkIn(h).ok, false, 'double check-in blocked');
assert.equal(L.redeem(r).ok, false, 'overspend blocked');
assert.equal(L.getStreak(h), 1);
const id = L.activeCheckInToday(h)!;
assert.equal(L.undo(id).ok, true);
assert.equal(L.getBalance(), 0);
assert.equal(L.getStreak(h), 0, 'undone check-in not in streak');
assert.equal(L.undo(id).ok, false, 'double undo blocked');
assert.equal(L.checkIn(h).ok, true, 'can re-check-in after undo');
const h2 = saveHabit({ name: 'Run', points: 5, reminder_time: null });
L.checkIn(h2); // balance 15
assert.equal(L.redeem(r).ok, true);
assert.equal(L.getBalance(), 0);
assert.equal(L.undo(L.activeCheckInToday(h)!).ok, false, 'cannot undo points already spent');
const redeemId = L.getLedger()[0].id;
assert.equal(L.undo(redeemId).ok, true, 'undo redeem refunds');
assert.equal(L.getBalance(), 15);
const rev = L.getLedger().find(e => e.type === 'REVERSAL')!;
assert.equal(L.undo(rev.id).ok, false, 'reversal cannot be undone');
console.log('all ledger checks passed, balance', L.getBalance());
